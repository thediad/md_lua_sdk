// Extract the bundled SGDK default font as 96 one-bit 8x8 glyphs.
// Regenerate after changing the pinned toolchain: node scripts/generate-bitmap-font.mjs
import { readFileSync, writeFileSync } from "node:fs";
// pngjs is included by the pinned romdev runner/host dependency.
import { PNG } from "pngjs";

const source = new URL("../node_modules/romdev-toolchain-m68k-gcc/share/genesis/lib/sgdk/res/image/font_default.png", import.meta.url);
const { width, height, data: rgba } = PNG.sync.read(readFileSync(source));
if (width !== 128 || height !== 48) throw new Error("Unexpected SGDK font dimensions");
const glyphs = [];
for (let glyph = 0; glyph < 96; glyph++) {
  const rows = [];
  for (let y = 0; y < 8; y++) {
    let bits = 0;
    for (let x = 0; x < 8; x++) {
      const offset = (((glyph >> 4) * 8 + y) * width + (glyph & 15) * 8 + x) * 4;
      if (rgba[offset + 3] && (rgba[offset] || rgba[offset + 1] || rgba[offset + 2])) bits |= 128 >> x;
    }
    rows.push(bits);
  }
  glyphs.push(`    {${rows.join(",")}}`);
}
writeFileSync(new URL("../md-sdk/md_font.h", import.meta.url),
  "// Generated by scripts/generate-bitmap-font.mjs from SGDK res/image/font_default.png.\n" +
  "// Same ASCII 32-127 font as SGDK hardware text; 768 ROM bytes, no RAM cache.\n" +
  `static const unsigned char md_font[96][8] = {\n${glyphs.join(",\n")}\n};\n`);
